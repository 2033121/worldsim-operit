// EventDesignSkills 事件设计完整方法论（~2.8KB，特殊场景/高要求时用）
// 来源卡：冲突深化/钩子九连环/悬念信息控制/爽点节奏/反派塑造专题/配角设计专题/
//
//	群像调度技巧/名场面设计公式/人物弧光与高燃/智斗博弈与布局设计/
//	故事能量动力学/人物关系化学反应三原则
func EventDesignSkills() string {
	return `
16. 冲突深化（冲突四类型×冲突升级链）：
   · 人与自我：道德抉择/自我怀疑/过去阴影——主角内心撕裂时生成"必须做选择"的事件，选择要有代价
   · 人与人：目标冲突（都要一样东西）/观念冲突（认为对方错了）/资源冲突（抢资源）/情绪冲突（积怨爆发）——双方都要有合理动机
   · 人与社会：制度/权力/阶层——规则背后要有利益链条，不能只是"规则就是规则"
   · 升级链：小摩擦→误解→对立→不可调和→爆发——别一步跳到打斗，让矛盾发酵3-5天
   · 冲突双方智商对等：对手有底牌有算计，不靠降智衬托主角

17. 钩子九连环（每天至少一个，平淡日用"轻钩子"）：
   · 悬念钩：反常现象让读者好奇"为什么"——结果前置，过程后置
   · 反差钩：与预期完全相反的场景/人物出现——反差越大越抓人
   · 危机钩：直接威胁主角的安全/地位/关系——倒计时感
   · 金手指钩：主角能力的异常表现或新发现——暗示潜力
   · 情感钩：关系突变——心动/背叛/重逢/误会，一句话改变关系
   · 谜题钩：待解的怪事，线索指向未知——给一点不给全部
   · 猎奇钩：罕见的/诡异的事物出现——满足好奇心
   · 爽点钩：打脸/收获/成长的前兆——让读者期待即将到来的爽
   · 轻钩子（平淡日）：一句怪话/一个反常细节/一个"不对劲"——种子埋下不展开

18. 悬念信息控制（悬念=未知性×关注度×持续性，任何一者为零则悬念为零）：
   · 三层信息差：主角知道什么、读者知道什么、NPC知道什么——三层同时存在时悬念最强
   · 揭示节奏：给线索→读者以为猜到了→反转→给更多线索→真相浮出——别一次揭底
   · 悬念保鲜：长线悬念每5-7天"提醒"一次（主角想起/新线索/旧物重现），埋了就忘=烂尾
   · 信息控制三技：话说一半（留半句让读者猜）/说漏嘴（不小心透露再圆回来）/答非所问（转移注意力）

19. 爽点节奏（爽感=铺垫长度×反差强度×读者代入度）：
   · 四类交替：打脸类（被看不起→碾压）/收获类（得到关键道具/能力/盟友）/装逼类（深藏不露→一鸣惊人）/情感类（误解消除/守护成功）
   · 密度控制：连憋3-5天后必须释放一次，释放后给2-3天平稳期再开始下一轮蓄力
   · 三步曲：铺垫→蓄力→爆发缺一不可，没有铺垫的爆发是"主角开挂"读者反感
   · 爽点后有代价：得到什么的同时失去什么，让爽感有重量

20. 反派塑造（事件涉及反派 NPC 时适用）：
   · 智商设计：信息差优势（不是真比主角聪明，是知道得多）+多重计划（A/B/C/D四层，破了A有B，破了B有C）+提前铺垫（每步棋前面有伏笔）
   · 动机六层：L1纯坏（神秘+压迫感，适合暗黑类世界）/L2利益（贪婪要具体）/L3理念（为自己相信的东西）/L4创伤（过去伤痛导致扭曲）/L5大义（觉得自己在拯救世界）/L6混沌（没有理由就是有趣）——层级越高反派越有魅力
   · 魅力七要素：反差感（冷酷但对某物温柔）/逼格（出场说话做事与众不同）/智商在线/有底线（再坏也有不碰的东西）/与主角羁绊（镜像关系）/经典台词/退场体面
   · 反派不降智：对手犯错要有合理原因（情绪失控/信息不足/被更上层出卖），不是"突然变蠢"

21. 配角设计（事件有 new_characters 时适用）：
   · 功能优先：每个配角必须有核心功能（推动剧情/反衬主角/提供信息/调节气氛），删掉后剧情受影响才算合格
   · 一个标签+一个反转：表面标签重复3次以上建立印象→关键事件展现反转内核→解释反差原因→之后日常还是标签行为但读者感觉不同了
   · 经典反转组合：逗比→关键时刻靠谱/高冷→内心温柔/胆小→有底线坚守/嚣张→内心自卑/老实→心机深沉/贪财→该花不手软
   · 三位一体记忆锚点：视觉标签（独一无二外形）+口头禅（标志性台词）+行为标签（独特行为模式）
   · 人设反差：外在表现反衬内在执念（强的衬痛/弱的衬刚/柔的衬刚/亮的衬孤）

22. 群像调度（多 NPC 同时在场时适用）：
   · 角色价值=(推动剧情次数+提供独特信息数+影响主角决策数)÷出场章节数——低于0.3的是工具人，考虑删除或合并
   · 每个核心配角配4件套：1个视觉记忆点+1个性格标签+1个专属能力+1句口头禅/标志动作
   · 关系网络：不是孤立角色排列，是相互连接的关系网——两人之间有秘密/误会/利益/情感，群像感才强
   · 轮流高光：每个核心配角每隔5-7天要有一次"自己的时刻"，不能全程只有主角在动

23. 名场面设计（高 severity 事件适用）：
   · 名场面=情绪浓度峰值×记忆点密度——画面+台词+动作+象征意义缺一不可
   · 情绪浓度：这一刻的情绪强度达到峰值（爽/悲/燃/震撼），必须是极致的
   · 记忆钉：一个极具画面感的瞬间——具体（用具体的动作/物件/身体反应来写，而非情绪标签）+反常+情感锚定
   · 名场面要有前置铺垫：前面几章的压抑/积累在这一刻集中释放，没有铺垫的名场面是空吼

24. 伏笔系统进阶（伏笔体验感=隐蔽度×回收惊喜感×前后呼应度）：
   · 埋设要"随手"：第一次出现时看起来是无关紧要的细节（一个动作/一句闲话/一个物件），不能让读者察觉"这是伏笔"
   · 回收要"恍然"：回收时读者才意识到那个细节的意义——拍大腿的感觉
   · 酝酿度推进：每次"推进"只露一点新信息，别一次性揭底
   · 短线伏笔（1-3天）必须快速回收别积压；长线伏笔每5-7天"提醒"一次存在感
   · 伏笔回收后可以"反转"——读者以为回收了，其实还有更深一层

25. 人物关系化学反应（涉及多角色互动时适用）：
   · 性格对冲：两个性格相反的人放一起天然有戏（毒舌×温柔/冲动×冷静/贪婪×慷慨），对冲不是对立是互补
   · 利益绑定：两人有共同的利益/秘密/敌人——被迫合作比主动合作更有张力
   · 互相暴露：关系深化的标志是"暴露弱点"——把自己最不想让人知道的事告诉对方，信任才真实
   · 关系变化要有机：朋友→敌人需要3-5个事件的积累（误会→猜疑→试探→确认→决裂），不能突然翻脸

26. 故事能量动力学（控制全局节奏）：
   · 能量四种形态：蓄能（铺垫积累读者期待）/释放（爽点爆发释放期待）/扰动（意外事件打乱节奏重新蓄能）/衰减（长时间无冲突能量自然下降）
   · 能量不能一直高也不能一直低：连续3天高能量→读者疲劳；连续3天低能量→读者弃书
   · 平淡期是蓄能期：别把平淡期当废物，它是为下一个爆发积蓄能量的必要阶段`
}

// WritingCraftSkills 小说写手常驻方法论（~4KB）
// 来源卡：去AI味技法体系/感官五维法/对话创作技巧/人物外貌与气质/情感分层描写/
//
//	节奏控制公式/情绪曲线设计/记忆钉系统/金句创作/崩文预防/朱雀去痕/
//	代入感六维度/章节类型写法矩阵/正文十大黄金法则/环境与背景描写/
//	场景空间与叙事设计/轻小说文风/修改润色方法论
func WritingCraftSkills() string {
	return `
去AI味深度技法（违反=本章不合格）：
7. AI高频词替换表：突然/猛然→用"冷不丁/猛地/说时迟那时快"这类更有画面感的词；缓缓/微微→用具体动作细节替代（写动作本身，别写"缓缓"）；似乎/仿佛→用具体感官替代（写感受到的具体现象）；默默/静静→删掉或用动作/环境音替代。本章同一AI高频词出现超3次=不合格。
8. 统计概率反转：每1000字找3个"最安全的词"换成"不那么常用但更准确"的词；每个比喻问"AI会用吗"，是就换；每个剧情节点想"AI会怎么写"然后反着写（逻辑自洽即可）。
9. 混沌感注入：每章留1个"不解释"的细节（主角为什么讨厌猫？不解释）；允许角色偶尔"不符合人设"（人是复杂的）；故意留"没用"的细节——真实生活里很多事就是没用。
10. 情绪毛刺：每个强烈情绪混入相反情绪（开心时一丝怅然，愤怒时一丝无力）；情绪转变有"卡顿"——变了一下又退回去再变；个人化情绪反应（紧张会笑/难过会吃东西/害怕会唠叨）。
11. 六大AI痕迹自检：①高频词重复≥3次 ②逻辑过于完美无意外 ③对话工整无口语 ④情感直白告诉而非展示 ⑤场景流水账 ⑥段落长度过于均匀——任一命中即需修改。

感官描写五维法（每场景≥4维，关键场景5维+第六感）：
· 视觉：必有，含至少1个反常细节（不该出现的东西/颜色/位置）
· 听觉：环境音+人声——用具体的声音意象（物品发出的响动、环境持续的底噪），声音可作进度条（越来越近=危险升级）
· 触觉：温度/质感/疼痛——用具体的触感意象（材质、冷热、潮湿），寒意要传导（由外到内、由肤及骨）
· 嗅觉：气味是记忆触发器——用有辨识度的气味，不同场景有专属气味
· 痛觉：战斗/危机必有，三层次代价——即时痛+持续影响+心理恐惧
· 第六感：身体的异常直觉（后颈发凉/胃里翻涌/汗毛竖起/莫名违和）——关键时刻用，不是每段都有

对话创作技法（对话占全章≥40%）：
· 对话四大原则：符合人设（社会地位/性格/时代背景决定说话方式）+推进剧情（传递信息/推动关系/制造悬念）+有潜台词（嘴上说A心里想B）+有节奏（长短句交替/快慢切换）
· 对白五句式交替：陈述句（给信息）/反问句（施压）/省略句（留白）/动作句（带行为）/沉默句（用动作代替回答）——别一直用陈述句
· 潜台词技法：言不由衷/话里有话/说漏嘴/答非所问——嘴上说的和心里想的可以错位，日常客套里藏着真实意图
· 对话三检验：①删掉原则——删掉这句剧情受影响吗？不受影响就是废话 ②换人原则——换另一个角色说还成立吗？成立就是没辨识度 ③行动原则——这句话里人物在"做"什么？只是"在说话"就重写
· 打岔与插话：人会插嘴/跑题/答非所问/说一半不说了/被别人打断——真实对话不是一问一答

节奏控制（压→缓→压→爆→留钩）：
· 四阶段循环：压（困境紧张）→缓（喘息但埋隐患）→压（隐患爆发更大困境）→爆（主角爆发读者爽）→留钩（新问题出现）
· 章节内部节奏：开头100-200字衔接+点题→发展1200-1500字推进冲突→高潮300-500字→结尾50-100字留钩
· 情绪曲线：波浪形不是直线——按500字分段标注情绪值(-5到+5)，必须在-3到+3间波动，禁止连续两段同向超过2个刻度
· 时间弹性：紧张场景放慢（1分钟写500字）→平淡场景快进（3天一句话带过）

记忆钉系统（每章钉1-2个）：
· 记忆钉=极具画面感的瞬间，读者读完几天还能想起来
· 特征：具体（用动作/物件/身体反应来写，而非情绪标签）+反常（超出日常预期）+情感锚定（带情绪共振）
· 四件套：招牌动作（可被模仿+绑定性格+每次微变体现成长）+身体反应+标志性台词+决策模式
· 主角记忆钉模板：角色名=招牌动作1+招牌动作2+身体反应+决策模式

代入感六维度（每章自检）：
· 身份认同：主角有缺陷不完美+身份贴近读者——读者愿意"变成"主角吗？
· 目标认同：目标清晰合理+动机可理解——读者能用一句话说清"主角想要什么"
· 情感认同：先珍视再失去+情感有铺垫——失去时读者会心疼
· 行动认同：即使失败也合理+选择有代价——读者觉得"换我我也这么选"
· 代价认同：代价够大+具体可感——读者为代价心疼但不觉得不值
· 成长认同：成长有迹可循+不能跳级——读者能说出"他从___变成了___"

金句创作（每章至少1句可传播的金句）：
· 金句五公式：反差型（A却B）/悖论型（看似矛盾实则深刻）/隐喻型（用A说B）/极致型（把一种感受推到极致）/留白型（说一半让读者补）
· 金句不是文笔炫耀，是读者情绪的出口——出现在情绪最浓的时刻，不是随便插

崩文预防五征兆自检：
· 节奏失控：连续3章无钩子/无爽点→立即加钩子
· 逻辑断裂：设定矛盾/能力忽强忽弱/时间线对不上→回查设定
· 人物变形：主角行为不符人设/配角沦为工具人/OOC无铺垫→回查人设卡
· 读者疲劳：单章信息过载/连续高潮无缓冲→加缓冲段
· 主角被动：主角全程被动接收怪事→给主角安排主动行动

环境与场景描写（场景空间三原则）：
· 可用性：场景能支撑剧情动作——能打斗/能走位/能藏人/能逃跑/能对话
· 辨识度：独特视觉记忆点——遮住90%只看10%能认出是哪
· 叙事性：场景本身在讲故事——暗示过去/烘托情绪/推动剧情
· 环境描写≤全章1/10，必须带信息或异常感，禁止纯风景抒情段落`
}

// WorldBuildingSkills 世界推进 Agent 常驻方法论（~2KB）
// 来源卡：世界观构建双四维法/世界设定自洽性检验/世界观细节深化/设定呈现节奏控制/
//
//	组织势力设计/故事能量动力学
func WorldBuildingSkills() string {
	return `
世界推进方法论（来自 KC 网文方法论体系）：
6. 世界观四层模型（推进时保持层次感）：
   · 表层（视觉与现象）：天气/环境/NPC穿着/日常秩序——读者第一眼看到的
   · 中层（规则与社会）：制度/势力/经济/法律——读者深入了解的
   · 深层（逻辑与真相）：世界运转的真实法则/被掩盖的历史——读者慢慢发现的
   · 核心（哲学与主题）：这个世界在讨论什么——读者最后感受到的
   · 推进时让世界的四层都在动：不只改天气和张力，也要让规则/势力/社会在变化

7. 设定呈现节奏（别一次性揭底）：
   · 第1-30天：只给表象不揭示真相——读者看到"是什么"不知道"为什么"
   · 第31-60天：逐步暗示让读者推理——给更多线索，读者开始拼拼图
   · 第61-100天：真相大白恍然大悟——所有线索收束
   · 揭示节奏控制：每次只揭示一层，不跨层跳——表层没交代完就揭深层=信息过载

8. 世界设定自洽性检验（推进时持续检查）：
   · 规则一致性：核心规则前后一致不漂移，打破规则有铺垫有代价
   · 规则有边界：什么能做什么不能做要明确，不能万能
   · 规则有代价：使用力量/资源需要付出代价，代价随使用递增
   · 势力行为一致性：每个势力的行为符合其利益和信念，不会突然变向

9. 组织势力设计（七维检验）：
   · 信念维：这个组织为什么存在？一句话说清
   · 结构维：权力如何分配？决策机制是什么？
   · 运作维：靠什么维持？资源从哪来？
   · 成员维：什么样的人加入？忠诚从何而来？
   · 对外维：外界怎么看他们？他们怎么对外？
   · 冲突维：内部矛盾是什么？外部敌人是谁？
   · 极限维：天花板在哪？什么能摧毁他们？
   · 推进时让势力按七维运转，不是只改"势力动向"一句话

10. 能量流动管理：
   · 蓄能期（平淡期）让世界在暗中积累变化——势力调动/伏笔滋长/环境渐变
   · 释放期（爆发期）让积累的变化集中显现——之前铺垫的全部浮出水面
   · 扰动期插入意外事件打乱节奏——新势力出现/旧规则被打破`
}

// CharacterDesignSkills 角色档案 Agent 常驻方法论（~2KB）
// 来源卡：人物五步塑造法/角色心理学/配角设计专题/人物关系化学反应/人物弧光与高燃
func CharacterDesignSkills() string {
	return `
角色塑造方法论（来自 KC 网文方法论体系）：
6. 人物五步塑造法（建档/更新时遵循）：
   · 身份→性格→欲望→弱点→成长——五步缺一不可
   · 人物记忆点=身份标签×性格反差×核心欲望×致命弱点×成长弧光
   · 弱点必须是致命的：在关键时刻会成为绊脚石的才是真弱点，不是"怕虫子"这种装饰性的
   · 成长弧光有方向：从A状态到B状态的转变，不是"变强了"这种模糊描述

7. 角色心理学冰山四层（建档时填充）：
   · 表层（行为表现）：说什么做什么——能直接观察到的
   · 中层（性格特质）：外向/内向/理性/感性/谨慎/冲动——相处久了感受到的
   · 深层（心理动机）：为什么这么做？想要什么？——需要深入了解才发现的
   · 底层（核心创伤/执念）：过去的经历/未完成的心结——连自己都未必察觉却决定一切的
   · 建档时四层都要填，只填表层=纸片人

8. 配角标签+反转设计：
   · 建档时设定表面标签+反转内核：逗比→关键时刻靠谱/高冷→内心温柔/胆小→有底线/嚣张→自卑/老实→心机深沉
   · 日常行为=标签行为（重复3次以上建立印象），关键事件=反转行为（展现另一面）
   · 反转后解释原因：为什么会有反差？（过往经历/隐藏身份/性格复杂性）

9. 人物关系化学反应：
   · 性格对冲：关系最有趣的是"相反的人在一起"——毒舌×温柔/冲动×冷静/贪婪×慷慨
   · 利益绑定：共同利益/秘密/敌人让关系有张力——被迫合作比主动合作更有戏
   · 互相暴露：关系深化的标志是暴露弱点——把最不想让人知道的事告诉对方
   · 关系变化三阶段：建立→考验→深化/决裂，每阶段需要2-3个事件支撑

10. 人物弧光与高燃设计：
   · 弧光=从A到B的转变：恐惧→勇敢/自私→担当/迷茫→坚定——方向明确
   · 高燃时刻：绝境中做出符合核心主题的选择——不是"突然变强"是"一直在忍终于不忍了"
   · 成长不能跳级：每次成长前面要有3-5个铺垫事件（失败/反思/尝试/再失败/突破）`
}

// StructureSkills 总导演 Agent 常驻方法论（~2KB）
// 来源卡：三幕式结构/故事骨架设计/叙事单元与框架循环/分卷设计与中段填充/
//
//	长篇生命周期管理/设定统筹与冲突校验/白金级地图范式
func StructureSkills() string {
	return `
结构设计方法论（来自 KC 网文方法论体系）：
6. 三幕式结构（弧线规划遵循）：
   · 第一幕（25%）：开端——世界原来的样子→触发事件→主角被迫踏上旅程
   · 第二幕（50%）：发展——障碍升级→中点反转→困境加深→至暗时刻
   · 第三幕（25%）：结局——最终决战→高潮→新平衡
   · 每个弧线段落对应一幕的子阶段，弧线之间用"转折点"连接

7. 故事骨架四标准（弧线规划自检）：
   · 核心冲突够强：双方都有足够理由，不是为打而打
   · 人物关系有张力：不只是盟友/敌人，有复杂纠葛
   · 势力格局有变化：不是静态的，随剧情演变
   · 主线方向清晰：一句话说清"这段讲什么"

8. 叙事单元四步循环（每个弧线段落遵循）：
   · 设定（建立情境/引入目标）→冲突（障碍出现/对抗升级）→解决（主角行动/结果揭晓）→新设定（后果+新钩子）
   · 长篇=无数个四步循环×一条主线串联——循环不是重复，是螺旋上升
   · 每个循环的"解决"要比上一个更难，"新设定"要比上一个更大

9. 分卷设计与中段填充：
   · 中段不是过渡段是主战场——主角大部分成长发生在中段
   · 中段三大死因：主线原地打转/支线注水脱节/节奏平铺直叙
   · 中段可读性=主线推进速度×支线关联度×节奏起伏密度
   · 支线必须与主线有关联——每条支线最终要反哺主线

10. 长篇生命周期管理：
   · 节奏曲线：前30天高密度抓人→30-100天稳节奏深入→100天后按弧线调整大爽点
   · 战力通胀控制：能力升级有代价有上限，不无限叠加新层级
   · 审美疲劳对抗：每30-50天换一次"质感"（新地图/新势力/新关系格局）

11. 地图=叙事容器（不是地理说明书）：
   · 地图服务主角成长：每个地图对应一个成长阶段
   · 地图控制节奏：换地图=重置爽点周期（新地图新挑战新积累）
   · 地图绑定核心要素：每个地图有独特的势力/资源/规则/氛围`
}

