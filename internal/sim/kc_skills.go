// EventContextSkills 根据事件类型动态注入详细方法论
func EventContextSkills(eventType string) string {
	switch eventType {
	case "conflict", "rival":
		return `
【冲突事件详细指南】
· 冲突升级四阶段：小摩擦（言语/态度）→误解（信息差）→对立（行动对抗）→不可调和（你死我活）——当天的事件如果是冲突升级，要明确当前在第几阶段
· 智斗三层：信息不对称（你知道的/我知道的/你以为我知道的）+心理博弈（预判对方的预判）+多层布局（A计划被破→B计划→C计划）
· 冲突要有"代价预览"：让读者看到冲突失败的后果有多严重，紧张感才真实`
	case "mystery":
		return `
【悬疑事件详细指南】
· 悬念三要素：未知性（读者不知道答案）+关注度（读者在乎答案）+持续性（答案不马上揭晓）
· 线索设计：给一点→读者以为猜到了→反转→给更多——当天的mystery事件只给"第一层线索"
· 诡异感来源：日常事物出现异常（熟悉+陌生=最恐怖）——不是"鬼"可怕，是"不应该在那里的东西"可怕`
	case "crisis", "disaster":
		return `
【危机事件详细指南】
· 名场面公式：情绪浓度峰值×记忆点密度——危机事件应该是"读者会记住的那个瞬间"
· 危机三要素：威胁具体（谁/什么/在哪里/多严重）+倒计时感（时间窗口在缩小）+主角被迫行动（没有退路）
· 危机后的余波：危机事件后1-2天要有"余震"——角色心理创伤/世界状态改变/关系因危机变化`
	case "revelation":
		return `
【真相揭示事件详细指南】
· 揭示节奏：只揭示一层——表层→中层→深层→核心，当天的revelation只揭一层不跨层
· 揭示方式：主角自己拼出来的（比NPC直接告诉更有爽感）+旧线索+新线索=真相
· 揭示后要有新谜题：揭开一个谜底的同时暴露更大的谜——"原来如此……但等等，那为什么会……"`
	case "romance":
		return `
【情感事件详细指南】
· 关系化学反应：性格对冲（相反的人在一起有戏）+利益绑定（共同秘密/敌人）+互相暴露（暴露弱点=信任）
· 情感进展不能跳级：陌生人→好感→心动→确认→深化——每步需要2-3个事件支撑
· 情感描写要分层：不是直接说情绪，而是写表情/动作/心理的细微变化——让读者自己感受到那个感觉是真的`
	}
	return ""
}

// NovelContextSkills 根据场景类型动态注入详细写作技法
func NovelContextSkills(hasBattle, hasEmotion, hasDialogue bool) string {
	var result string
	if hasBattle {
		result += `
【战斗场景写作详细指南】
· 五镜头法：全景（环境+双方位置）→中景（交锋动作）→特写（关键一击/表情/细节）→慢镜头（决定性瞬间）→余韵（战后状态）
· 动作动词优先：推/攥/蹲/劈/挡/滚/撞——一个动词一个画面，少用形容词堆叠
· 战斗节奏：短句快节奏（交手中）+长句慢节奏（对峙/观察时）交替
· 伤害描写三层次：即时痛（具体部位+痛感比喻）+持续影响（动作变形/反应变慢）+心理代价（恐惧/决心）
· 武器有性格：角色选什么武器=角色是什么人——武器不只是工具是性格延伸`
	}
	if hasEmotion {
		result += `
【情感场景写作详细指南】
· 情感三层模型：表层（表情/动作/语气）→中层（心理活动/回忆闪回）→深层（身体反应/本能）
· 情绪不是直线：开心→一丝不安→更开心→突然心酸→释然——波浪形不是直线
· 情感锚点：用一个具体物件/动作/气味锚定情感——让记忆里的东西带出情绪
· 留白比直白有力：不直接说情绪词，用动作/细节让读者自己感受到`
	}
	if hasDialogue {
		result += `
【对话场景写作详细指南】
· 对话=行动：每句话人物在"做"什么（试探/威胁/讨好/隐瞒/炫耀/哀求/挑衅）
· 三检验：删掉原则（删了剧情受影响吗）+换人原则（换人说还成立吗）+行动原则（只是在说话还是有目的）
· 对话节奏：快（连续短句交锋）→慢（长句+心理活动）→快（爆发）——像音乐有快有慢
· 沉默也是对话：不说话+一个动作比说十句话更有力——"他没接话，把杯子推过去"`
	}
	return result
}
